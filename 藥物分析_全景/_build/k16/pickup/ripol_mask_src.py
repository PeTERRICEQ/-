def report(name, M, total, v0, v1):
    assert len(M) == total, (name, len(M))
    q = json.load(open(os.path.join(HERE, "..", "藥分_100-115_1280題.json"), encoding="utf-8"))
    ids = {x["id"] for x in q if x["ch"][0] == name}
    assert ids == set(M), (name, ids ^ set(M))
    c = Counter(v["t"] for v in M.values())
    ok = c["Y"] + c["2"]
    print(f"{name}: {total} 題  Y {c['Y']}  2 {c['2']}  N {c['N']}  Y＋2＝{ok}／{total}＝{ok/total*100:.1f}%")
    print("  ", dict(sorted(Counter((v["E"], v["t"]) for v in M.values()).items())))
    for half, f in (("100–107", lambda i: int(i[:3]) <= 107), ("108–115", lambda i: int(i[:3]) >= 108)):
        sub = [v for i, v in M.items() if f(i)]
        k = sum(v["t"] in "Y2" for v in sub)
        print(f"   {half}: {k}／{len(sub)}" + (f"＝{k/len(sub)*100:.1f}%" if sub else ""))
    print(f"   v0 {len(v0)}／{total}  v1 {len(v1)}／{total}  本版 {ok}／{total}")
    print("   N:", [i for i, v in M.items() if v["t"] == "N"], " 2:", [i for i, v in M.items() if v["t"] == "2"])
    json.dump(dict(sorted(M.items())), open(os.path.join(HERE, f"{name}_mask.json"), "w", encoding="utf-8"), ensure_ascii=False, indent=1)

