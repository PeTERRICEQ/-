def _n(eng):
    return sum(x["n"] for x in _LAND.get(eng, []))


def _land_cell(eng):
    xs = sorted(_LAND.get(eng, []), key=lambda x: -x["n"])
    return "、".join(f'{x["chn"]} {x["n"]}' for x in xs)


def _mask_rows():
    rows = []
    for k in ORDER:
        m = _MASK.get(k)
        if not m:
            continue
        ok = m["Y"] + m["two"]
        pct = ok / m["n"]
        tone = "grn" if pct >= 0.9 else ("org" if pct >= 0.85 else "red")
        rows.append([CHN[k], str(m["n"]), str(m["Y"]), str(m["two"]), str(m["N"]), (f"{pct:.0%}", tone, 700),
                     f'{m["old"][0]}/{m["old"][1]}', f'{m["new"][0]}/{m["new"][1]}'])
    return rows


