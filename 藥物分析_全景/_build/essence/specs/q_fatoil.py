def _pages(T):
    pages = [_SUMMARY]
    for i in range(0, len(T), 4):
        g = T[i:i + 4]
        rng = f'{g[0]["no"]}～{g[-1]["no"]}' if len(g) > 1 else g[0]["no"]
        d = [_drill(t) for t in g]
        s = [_sol(t) for t in g]
        pages.append(dict(label="④ 題型練習", sub=f"{rng}：先寫本體，再推一次", cols=[0.5, 0.5],
                          read="遮住下一頁的詳解。每張卡先寫這題考哪個本體，再從本體推到答案，推完再翻頁",
                          left=d[0:2], right=d[2:4]))
        pages.append(dict(label="④ 題型詳解", sub=f"{rng}：從本體一步一步推到答案", cols=[0.5, 0.5],
                          read="和上一頁同位置對照。推導鏈第 1 步是本體，之後每步一個箭頭，推錯的那一步回 ① 找本體",
                          left=s[0:2], right=s[2:4]))
    return pages


