def _drill(t):
    return dict(type="drill", no=t["no"], name=t["name"], E=t["E"], n=len(t["ids"]), src=t["src"],
                stem=t["stem"], opts=t["opts"], lines=t.get("lines", 6))


def _sol(t):
    d = dict(type="sol", no=t["no"], name=t["name"], ans=t["ans"], chain=t["chain"], why_not=t["why_not"], var=t["var"])
    if t.get("trap"):
        d["trap"] = t["trap"]
    return d


def _rows(ch):
    return [[(t["no"], "ink", 700), t["name"], t["E"], str(len(t["ids"])), t["src"], "、".join(i for i, _ in t["var"])]
            for t in TYPES if t["ch"] == ch]


def _cov(ch):
    n = sum(len(t["ids"]) for t in TYPES if t["ch"] == ch)
    return n, NCH[ch]


