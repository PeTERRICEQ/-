def group_pages(grp, tag):
    rng = f'{grp[0]["no"]}–{grp[-1]["no"]}' if len(grp) > 1 else grp[0]["no"]
    h = 2 if len(grp) == 4 else (len(grp) + 1) // 2
    L, Rt = grp[:h], grp[h:]
    return [dict(label="④ 題型練習", sub=f"{tag} {rng}：先寫本體，再推一次",
                 read="遮住下一頁。① 寫這題考哪個本體，② 從本體一步一步推到答案，再翻頁對照。",
                 cols=[0.5, 0.5], left=[drill(t) for t in L], right=[drill(t) for t in Rt]),
            dict(label="④ 題型詳解", sub=f"{tag} {rng}：推導鏈從本體出發",
                 read="逐步核對推導鏈，找出第一個推錯的步驟，推錯的步驟回 ① 找本體。歷年變形題號都是同一題型的真題。",
                 cols=[0.5, 0.5], left=[sol(t) for t in L], right=[sol(t) for t in Rt])]


def pages():
    out = [SUMMARY]
    for g in range(0, len(T), 4):
        out += group_pages(T[g:g + 4], "IR")
    out += group_pages(R, "Raman")
    return out


