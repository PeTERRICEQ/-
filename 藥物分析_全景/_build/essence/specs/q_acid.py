def _drill(t):
    return dict(type="drill", no=t["no"], name=t["name"], E=t["E"], n=len(t["ids"]), src=t["src"],
                stem=t["stem"], opts=t["opts"], lines=t.get("lines", 6))


def _sol(t):
    return dict(type="sol", no=t["no"], name=t["name"], ans=t["ans"], chain=t["chain"],
                why_not=t["why_not"], var=t["var"], trap=t.get("trap"))


